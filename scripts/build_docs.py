"""Rebuild docs/variables.md: every variable of the controller, from the portal's public configuration file.

Names, types and how the integration uses them; no value of any installation and none of ÖkoFEN's own texts
(those are downloaded by the integration at run time). Same source as scripts/build_catalog.py.

    python scripts/build_docs.py
    OEKOFEN_LOCAL_HOST=192.168.0.10 OEKOFEN_LOCAL_PASSWORD=... python scripts/build_docs.py   # + docs/local.md
"""

from __future__ import annotations

import collections
import http.client
import json
import os
import pathlib
import re
import sys
import time
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "custom_components"))

from okofen_portal.catalog import group_of, split_group  # noqa: E402
from okofen_portal.const import DASHBOARD, FAST_VARIABLES  # noqa: E402
from okofen_portal.docs import CONFIG_URL  # noqa: E402
from okofen_portal import local  # noqa: E402
from okofen_portal.local import LOCAL_SETTINGS, MAP  # noqa: E402
from okofen_portal.names import Texts  # noqa: E402
from okofen_portal.settings import SETTING_BY_KEY  # noqa: E402
from okofen_portal.solar_boost import KEYS as BOOST_KEYS  # noqa: E402

OUT = ROOT / "docs" / "variables.md"
# how a group is titled, in the order of the page
SECTIONS = {
    "hk": "Heating circuits `hk[n]`", "ww": "Hot water `ww[n]`", "pu": "Buffer tanks `pu[n]`",
    "sk": "Solar circuits `sk[n]`", "boiler": "Existing boiler `ke_`, `bestke_`", "fa": "Pellet boilers `FA[n]`",
    "weather": "Weather `weather_`", "system": "System and other functions",
}


def walk(node):
    if isinstance(node, dict):
        yield node
        for value in node.values():
            yield from walk(value)
    elif isinstance(node, list):
        for value in node:
            yield from walk(value)


def pattern(key: str) -> str:
    """'LOCAL.hk[2].zeitprogramm[1].tag[3]...' -> 'hk[n].zeitprogramm[1].tag[3]...': the instance becomes n."""
    name = key.removeprefix("LOCAL.")
    return re.sub(r"^(FA|(?:L_)?[a-z0-9]+)\[\d+\]", r"\1[n]", name, count=1)


def section(key: str) -> str:
    kind, _ = split_group(group_of(key))
    return kind if kind in SECTIONS else "system"


def main() -> None:
    with urllib.request.urlopen(CONFIG_URL, timeout=60) as resp:
        config = json.load(resp)
    types: dict[str, str] = {}
    for node in walk(config):
        variable = str(node.get("variable", "")).removeprefix("CAPPL:")
        if variable and "title" in node:  # a field of a menu (the rest are display conditions)
            types.setdefault(variable, node.get("valueType") or node.get("type") or "")
        elif variable:
            types.setdefault(variable, "")
    texts = Texts.load("en")
    local = {k: f"`{g}.{f}`" for k, (g, f, _, _) in MAP.items()}
    boost = {v: k for k, v in BOOST_KEYS.items()}
    panel = {v: k for k, v in DASHBOARD.items()}
    rows: dict[str, dict[str, list]] = collections.defaultdict(dict)
    for key in sorted(types):
        if not key.startswith(("LOCAL.", "FA[")):
            continue
        name = pattern(key)
        row = rows[section(key)].setdefault(name, [key, set(), set(), set()])
        if key in local:
            loc = local[key]
            if "[n]" in name:  # groups count from 1 locally (hk1 = hk[0]), the forecast from 0
                index = int(re.search(r"\[(\d+)\]", key).group(1))
                loc = re.sub(r"\d+", lambda m: "N" if int(m.group()) == index + 1 else "n", loc, count=1)
            row[1].add(loc)
        uses = row[2]
        if key in SETTING_BY_KEY:
            uses.add(f"set ({SETTING_BY_KEY[key].platform})")
        if key in LOCAL_SETTINGS:
            uses.add("set locally")
        if key in FAST_VARIABLES:
            uses.add("30 s")
        if key in panel:
            uses.add(f"panel `{panel[key]}`")
        if key in boost:
            uses.add(f"solar boost `{boost[key]}`")
        row[3].add(types[key])
    lines = [
        "---", "title: Variable reference", "---", "",
        "# Variable reference", "",
        "Every variable the portal's web app knows, grouped by function, generated by `scripts/build_docs.py` "
        "from the portal's public configuration file. See [Parameters and nomenclature](parameters.md) for how to "
        "read the names.", "",
        "- **Variable**: the portal name, after `CAPPL:LOCAL.` (or `CAPPL:` for `FA[n]`); `[n]` is the instance "
        "(0 for the first circuit). `L_` names are measurements and states, read only; the others are settings.",
        "- **Name**: the English name the integration gives it (words it has no translation for are left in German).",
        "- **Local JSON**: the field of the controller's local interface, when it has one (`N` = n + 1).",
        "- **Type**: `number`, `options` (an index into a list of states), `time` / `simpletime` (HHMM) or "
        "`comfortzeit` (a schedule slot); empty when the portal only reads it.",
        "- **Integration**: *30 s* polled often (otherwise every 5 min), *set* writable from Home Assistant, "
        "*set locally* written through the local interface, *panel* / *solar boost* the short name used there.",
        "",
        f"{sum(len(r) for r in rows.values())} variables (instances collapsed) out of {len(types)} names.",
        "",
    ]
    lines += [f"- [{SECTIONS[s]}](#{re.sub(r'[^a-z0-9 -]', '', SECTIONS[s].lower()).replace(' ', '-')})" for s in SECTIONS if s in rows]
    for sec, title in SECTIONS.items():
        if sec not in rows:
            continue
        lines += ["", f"## {title}", "", "| Variable | Name | Local JSON | Type | Integration |", "|---|---|---|---|---|"]
        for name, (key, loc, uses, kinds) in sorted(rows[sec].items(), key=lambda r: (r[0].split(".")[-1].startswith("L_"), r[0])):
            friendly = texts.friendly_name(key).replace("|", "/")
            lines.append(
                f"| `{name}` | {friendly} | {', '.join(sorted(loc))} | {', '.join(sorted(k for k in kinds if k))} "
                f"| {', '.join(sorted(uses))} |"
            )
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{OUT.relative_to(ROOT)}: {sum(len(r) for r in rows.values())} rows")
    if os.environ.get("OEKOFEN_LOCAL_HOST"):
        local_doc(os.environ["OEKOFEN_LOCAL_HOST"], os.environ["OEKOFEN_LOCAL_PASSWORD"])


LOCAL_OUT = ROOT / "docs" / "local.md"
LOCAL_GROUPS = {
    "system": "System", "weather": "Weather", "forecast": "Forecast", "hk": "Heating circuits `hkN`",
    "pu": "Buffer tanks `puN`", "ww": "Hot water `wwN`", "sk": "Solar circuits `skN`",
}
DEFAULT_RANGE = (-32768, 32767)  # what the controller gives for a measurement without real bounds


def local_doc(host: str, password: str) -> None:
    """docs/local.md from the controller's own description (all?): fields, units, bounds, never the values."""
    for _ in range(10):  # urllib drops the empty query of "all?", http.client sends the path as is
        conn = http.client.HTTPConnection(host, local.PORT, timeout=15)
        conn.request("GET", f"/{password}/all?")
        text = conn.getresponse().read().decode("latin-1")
        if not text.startswith("Wait at least"):
            break
        time.sleep(local.RATE_LIMIT / 2)
    meta = json.loads(text)
    portal = {(re.sub(r"\d+$", "", g), f): k for k, (g, f, _, _) in MAP.items()}  # any instance
    lines = [
        "---", "title: Local JSON interface", "---", "",
        "# Local JSON interface", "",
        "The fields of the controller's local interface (`http://<controller>:4321/<password>/all?`), generated by "
        "`scripts/build_docs.py` from the controller's own description, read on a Touch with JSON interface V4.00b. "
        "A plant with more circuits has `hk2`, `ww2`… with the same fields; groups this plant does not have (`pe` "
        "pellet boilers, `circ` circulation pumps, `se`, `thirdparty`, `power`, `stirling`) are not listed. "
        "See [Parameters and nomenclature](parameters.md) for how to read and write them.", "",
        "- **Factor**: the real value is the raw value times the factor (`225` × 0.1 = 22.5 °C); writes use the raw value.",
        "- **Range**: the bounds the controller accepts for a setting.",
        "- **Type**: `options` is an index into a list of states (in `all?`, in the controller's language); "
        "`text` a string; `status` a bit field.",
        "- **Access**: `L_` fields are read only.",
        "- **Portal**: the same variable on the portal, when the integration pairs them "
        "([variable reference](variables.md)).", "",
    ]
    for prefix, title in LOCAL_GROUPS.items():
        group = next((g for g in meta if re.fullmatch(rf"{prefix}\d*", g)), None)
        if group is None:
            continue
        lines += ["", f"## {title}", "", "| Field | Unit | Factor | Range | Type | Access | Portal | Integration |",
                  "|---|---|---|---|---|---|---|---|"]
        for field, spec in meta[group].items():
            if field.endswith("_info") or (group == "forecast" and field != "L_w_0"):
                continue
            spec = spec if isinstance(spec, dict) else {}
            rng = (spec.get("min"), spec.get("max"))
            kind = ("options" if "format" in spec else "text" if "length" in spec or not spec
                    else "status" if field == "L_state" else "number")
            name = "L_w_n" if field == "L_w_0" else field
            key = portal.get((prefix, field), "")
            uses = "set locally" if key in LOCAL_SETTINGS else "read every 10 s" if key else ""
            lines.append(
                f"| `{name}` | {spec.get('unit', '')} | {spec.get('factor', '')} "
                f"| {f'{rng[0]} to {rng[1]}' if None not in rng and rng != DEFAULT_RANGE else ''} | {kind} "
                f"| {'read only' if field.startswith('L_') else 'read / write'} "
                f"| {f'`{pattern(key)}`' if key else ''} | {uses} |"
            )
    LOCAL_OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{LOCAL_OUT.relative_to(ROOT)} written")


if __name__ == "__main__":
    main()
